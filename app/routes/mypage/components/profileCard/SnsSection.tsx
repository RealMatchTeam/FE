const INSTAGRAM_PREFIX = "https://www.instagram.com/";

const extractInstagramId = (value: string) => {
  const trimmed = value.trim();
  if (!trimmed) return "";

  const withoutAt = trimmed.replace(/^@/, "");
  const match = withoutAt.match(/instagram\.com\/([^/?#]+)/i);
  if (match?.[1]) return match[1];

  return withoutAt;
};

const toInstagramUrl = (value?: string | null) => {
  const id = extractInstagramId(value ?? "");
  return id ? `${INSTAGRAM_PREFIX}${id}` : "";
};

